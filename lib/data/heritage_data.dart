  static HeritageAttraction? byId(String id) {
    for (final attraction in attractions) {
      if (attraction.id == id) return attraction;
    }
    return null;
  }

  static String _normalise(String value) {
    return value
        .toLowerCase()
        .replaceAll(RegExp(r'[^a-z0-9 ]'), ' ')
        .replaceAll(RegExp(r'\\s+'), ' ')
        .trim();
  }

  static HeritageAttraction? findByVisionCandidates(List<String> candidates) {
    for (final rawCandidate in candidates) {
      final candidate = _normalise(rawCandidate);
      if (candidate.isEmpty) continue;

      for (final attraction in attractions) {
        for (final rawAlias in [attraction.name, ...attraction.aliases]) {
          final alias = _normalise(rawAlias);
          if (candidate == alias ||
              candidate.contains(alias) ||
              alias.contains(candidate)) {
            return attraction;
          }
        }
      }
    }
    return null;
  }
